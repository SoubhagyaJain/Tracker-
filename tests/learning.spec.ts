import { expect,test } from '@playwright/test';

test('a Udemy course updates roadmap learning analytics and survives backup restoration',async({page},info)=>{
  await page.clock.setFixedTime(new Date('2026-12-02T06:30:00Z'));
  await page.goto('/learning/');
  await page.getByRole('button',{name:'Add Udemy course',exact:true}).click();
  await page.getByLabel('Course title').fill('Python foundations');
  await page.getByLabel('Udemy course URL').fill('https://www.udemy.com/course/python-foundations/learn/lecture/10');
  await page.getByLabel('Enrollment status').selectOption('Active');
  await page.getByRole('button',{name:'Add course',exact:true}).click();
  await page.getByRole('link',{name:'Course details',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Python foundations'})).toBeVisible();
  await page.getByText('Edit course mapping', {exact:true}).click();
  await page.getByRole('combobox',{name:'Roadmap skill',exact:true}).selectOption('python');
  await page.getByRole('button',{name:'Save course mapping'}).click();
  await expect(page.getByRole('button',{name:/Python, OOP/})).toBeVisible();
  await page.getByRole('button',{name:'Update progress',exact:true}).click();
  await page.getByLabel('Total lectures').fill('2');
  await page.getByRole('button',{name:'Save progress',exact:true}).click();
  await page.getByText('Add curriculum section',{exact:true}).click();
  await page.getByLabel('New section title').fill('Python core');
  await page.getByRole('button',{name:'Add section',exact:true}).click();
  await page.getByText('Python core',{exact:true}).click();
  for(const title of ['Functions','Types']){
    await page.getByLabel('Lecture title').fill(title);
    await page.getByRole('button',{name:'Add lecture',exact:true}).click();
    await page.getByLabel(title,{exact:true}).check();
  }
  await expect(page.getByRole('img',{name:'Course completion: 100 percent'})).toBeVisible();
  await page.getByRole('button',{name:'Log course study'}).click();
  await page.getByLabel('Focused minutes').fill('60');
  await page.getByLabel('Measured video minutes').fill('25');
  await page.getByLabel('Start time (device time, optional)').fill('09:00');
  await page.getByRole('button',{name:'Save study time'}).click();
  await expect(page.getByRole('heading',{name:'Course study history'})).toBeVisible();
  await expect(page.getByText(/60 min focused · 25 min video/)).toBeVisible();
  await page.getByRole('button',{name:'Log course study'}).click();
  await page.getByLabel('Start time (device time, optional)').fill('09:00');
  await page.getByRole('button',{name:'Save study time'}).click();
  await expect(page.getByRole('alert')).toContainText('overlaps');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('button',{name:'Schedule course study'}).click();
  await page.getByLabel('Session title').fill('Python practice block');
  await page.getByRole('button',{name:'Save changes'}).click();
  await page.goto('/today/');
  await expect(page.getByText(/Python practice block/)).toBeVisible();
  await page.goto('/analytics/');
  const udemy=page.locator('section.panel').filter({has:page.getByRole('heading',{name:'Udemy learning analytics',exact:true})});
  await expect(udemy.getByText('1h focused',{exact:true})).toBeVisible();
  await expect(udemy.locator('.line-row').filter({hasText:'Python, OOP, standard library, typing'})).toContainText('1h');
  await page.reload();
  await expect(page.getByRole('heading',{name:'Udemy learning analytics'})).toBeVisible();
  await expect(udemy.getByText('0.4h',{exact:true})).toBeVisible();
  await page.goto('/settings/');
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export JSON backup'}).click();
  const backupPath=info.outputPath('learning-backup.json');
  await (await downloaded).saveAs(backupPath);
  await page.getByRole('button',{name:'Reset personal data',exact:true}).click();
  await page.getByRole('button',{name:'Reset data',exact:true}).click();
  await page.getByLabel('Choose backup file').setInputFiles(backupPath);
  await page.getByRole('button',{name:'Restore backup',exact:true}).click();
  await page.goto('/learning/');
  await page.getByRole('link',{name:'Course details',exact:true}).click();
  await expect(page.getByRole('img',{name:'Course completion: 100 percent'})).toBeVisible();
  await expect(page.getByText(/60 min focused · 25 min video/)).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  const overview=page.getByRole('link',{name:'AI Career OS overview'});
  await overview.click();
  await expect(page.getByRole('button',{name:'Python —',exact:true})).toBeVisible();
});

